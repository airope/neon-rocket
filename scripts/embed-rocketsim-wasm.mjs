import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const input = path.join(root, 'native/rocketsim/dist/rocketsim-raw.wasm');
// Optional destination supports audit/staging without changing the live shared bundle.
const output = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'shared/rocketsim-wasm-bundled.js');
const bytes = fs.readFileSync(input);
if (!WebAssembly.validate(bytes)) throw new Error('Refusing to embed invalid WebAssembly');
const base64 = bytes.toString('base64');
const source = `// Generated by scripts/embed-rocketsim-wasm.mjs — do not edit manually.\nconst BASE64 = '${base64}';\nlet cached;\n\nexport function bundledRocketSimWasm() {\n  if (cached) return cached;\n  const binary = atob(BASE64);\n  cached = new Uint8Array(binary.length);\n  for (let index = 0; index < binary.length; index++) cached[index] = binary.charCodeAt(index);\n  return cached;\n}\n`;
fs.writeFileSync(output, source);
console.log(`Embedded ${fs.statSync(input).size} WASM bytes in ${path.relative(root, output)}`);
